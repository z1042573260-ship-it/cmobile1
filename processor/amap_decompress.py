# 粗粒度 level：说明高德没匹配到具体地址、兜底退回了行政中心，必须拒绝
COARSE_LEVEL = {"省", "市", "城市", "区县", "省份", "国家"}

# 判断原 location 是否"笼统"（仅到区县/市，无道路/村/门牌等细节）
_GENERIC_RE = re.compile(r'^(烟台市\s*)?([一-龥]{2,4}(区|市|县)|开发区|高新区|烟台高新区|烟台开发区)$')
_FINE_MARKS = ('路', '街', '巷', '村', '镇', '号', '大厦', '小区', '大道', '工业区', '工业园',
               '园', '里', '庄', '委', '组', '栋', '楼', '广场', '市场', '学校', '医院',
               '公司', '厂', '库', '港', '站', '新区')

def is_generic_location(loc):
    """原 location 仅到区县/市（如『烟台市 莱山区』『龙口市』）视为笼统需更新；已含道路/村/门牌等细节则保留。"""
    if not loc:
        return True
    s = re.sub(r'^烟台市\s*', '', str(loc)).strip()
    if _GENERIC_RE.match(str(loc)) or _GENERIC_RE.match(s):
        return True
    if not any(w in s for w in _FINE_MARKS):
        return True
    return False

def norm_location(addr):
    """去掉『山东省/烟台市』前缀，保留『区县+详情』，与 workbuddy 原 location 风格一致。"""
    return re.sub(r'^(山东省)?(烟台市)?', '', addr).strip()

def _district_center(dist):
    """缓存各区县中心坐标，用于识别'兜底退回行政中心'的假解压。"""
    if not hasattr(_district_center, "cache"):
        _district_center.cache = {}
    if dist not in _district_center.cache:
        g = geocode(dist, "烟台市")
        _district_center.cache[dist] = (g["lng"], g["lat"]) if g else None
    return _district_center.cache[dist]

def decompress(json_path, verbose=True):
    d = json.load(open(json_path, encoding="utf-8"))
    idxmap = {r.get("_index"): r for r in d}
    # 强制重算的集合（已解压过的也重新编码，用于修正误落点/同步更新 location）；日常为空即跳过已解压项
    FORCE_REDO = set()
    ok = fail = skip = 0
    for k, addr in WEB_ADDR.items():
        r = idxmap.get(k)
        if not r:
            print(f"  [不在数据] _index={k}")
            fail += 1; continue
        if r.get("geo_source") == "网页增强(高德)" and k not in FORCE_REDO:
            skip += 1; continue
        # 真实区县与记录 district 不符时（如 168 实际在海阳），先修正 district 再编码
        real_dist = OVERRIDE_DISTRICT.get(k, r.get("district", ""))
        if k in OVERRIDE_DISTRICT:
            r["district"] = real_dist
        g = geocode(addr, "烟台市")
        accepted = False
        if g and (k in OVERRIDE_DISTRICT or region_ok(r.get("district", ""), g)):
            # 精度闸门：拒绝"兜底退回区县中心"的粗结果（level 粗 或 坐标仍与中心重合）
            c = _district_center(real_dist)
            same_center = c and abs(c[0] - g["lng"]) < 1e-4 and abs(c[1] - g["lat"]) < 1e-4
            if g.get("level") in COARSE_LEVEL or same_center:
                accepted = False
            else:
                accepted = True
        if accepted:
            new = {}
            for kk, vv in r.items():
                if kk in ("lng", "lat"):
                    continue   # 坐标由 g 决定，不复制旧的中心点坐标
                new[kk] = vv
            new["lng"] = g["lng"]; new["lat"] = g["lat"]
            new["geo_source"] = "网页增强(高德)"
            # location 更新：原仅到区县(笼统) 或 区县被 OVERRIDE_DISTRICT 修正的记录，
            # 同步更新为增强得到的详细地址；原已是详细地址(含道路/村/门牌)则保留不动
            if k in OVERRIDE_DISTRICT or is_generic_location(r.get("location", "")):
                new["location"] = norm_location(addr)
            r.clear(); r.update(new)
            ok += 1
            if verbose:
                print(f"  [OK] {k} {r.get('project_name','')[:18]} -> ({g['lng']},{g['lat']}) {g.get('level')}/{g.get('district')}")
        else:
            # 解压失败：保留原坐标，但如实标注，避免伪装成"网页增强"
            if r.get("geo_source") == "网页增强(高德)":
                r["geo_source"] = "区县中心(未能精确定位)"
            fail += 1
            if verbose:
                print(f"  [FAIL] {k} {r.get('project_name','')[:18]} | addr={addr} | level={g.get('level') if g else None}")
        time.sleep(SLEEP)
    json.dump(d, open(json_path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"解压完成：成功 {ok} | 失败(保留中心点) {fail} | 已解压跳过 {skip} | 本批 {len(WEB_ADDR)}")

