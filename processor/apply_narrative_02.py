EXCLUDE = [22, 26]  # 非建设工程，按管线要求排除

def main():
    with open(PATH, encoding="utf-8") as f:
        data = json.load(f)
    n0 = len(data)

    # 1) 覆盖叙述字段
    applied = []
    for idx, reason, summ, needs in NARR:
        rec = data[idx]
        rec["ai_reason"] = reason
        rec["ai_summary"] = summ
        rec["telecom_needs"] = needs
        applied.append(idx)

    # 2) 排除非建设工程（降序删除，避免下标漂移）
    removed = []
    for idx in sorted(EXCLUDE, reverse=True):
        removed.append((idx, data[idx].get("project_name", "")[:30]))
        del data[idx]

    # 3) 重新连续编号 _index
    for i, rec in enumerate(data):
        rec["_index"] = i

    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"原始条数: {n0} -> 现条数: {len(data)} (移除 {len(EXCLUDE)} 条非建设工程)")
    print("已覆盖叙述字段的原下标:", applied)
    print("已移除 (原下标, 项目名前30字):")
    for idx, name in removed:
        print(f"  #{idx}: {name}")
    print("第一条现内容:", data[0]["ai_reason"][:40], "...")

if __name__ == "__main__":
    main()
